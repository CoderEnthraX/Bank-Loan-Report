"""Generic hookeval rule: tight stop (max(0.9 ATR, beyond displacement extreme)) when SPEC is true.
SPEC grammar (features from fbank.feats / fbank2.feats2 computed at the displacement bar, no fill-bar features):
  ('atom', feat, '<'|'>', thr) | ('and', a, b) | ('or', a, b) | ('tree', feat, thr, no_spec, yes_spec)  (yes = feat > thr)
  | True | False.   Use make(SPEC, path) to write a module file."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)


def ev(spec, f):
    if spec is True or spec is False: return spec
    op = spec[0]
    if op == 'atom':
        v = f[spec[1]]; return v < spec[3] if spec[2] == '<' else v > spec[3]
    if op == 'and': return ev(spec[1], f) and ev(spec[2], f)
    if op == 'or': return ev(spec[1], f) or ev(spec[2], f)
    if op == 'tree': return ev(spec[4], f) if f[spec[1]] > spec[2] else ev(spec[3], f)
    raise ValueError(spec)


def featfn(P, i, d, entry):
    from fbase import base
    from fbank import feats
    from fbank2 import feats2
    base(P['sym'])
    f = feats(P, i, d, entry); f.update(feats2(P, i, d)); return f


TEMPLATE = '''"""hookeval rule generated by stop_tree/rulegen.py: tight stop when {desc}"""
import sys
sys.path.insert(0, {here!r})
from rulegen import ev, featfn
SPEC = {spec!r}
def stop_fn(P, i, d, entry, stop, A, ctx):
    if i < 700: return stop           # warm-up bars (ground truth starts at bar >= 1731)
    if ev(SPEC, featfn(P, i, d, entry)):
        ext = P['L'][i] if d > 0 else P['H'][i]
        return entry - d * max(0.9 * A, d * (entry - ext))
    return stop
'''


def make(spec, path, desc=''):
    open(path, 'w').write(TEMPLATE.format(desc=desc or repr(spec), here=HERE, spec=spec))
