"""Builds mql5rt.h = mql5shim.h (declarations) patched + rt_impl.h (implementations)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
h = open(os.path.join(HERE, "..", "mql5shim.h")).read()
def rep(a, b):
    global h
    assert a in h, a
    h = h.replace(a, b)
for nm, ty in (("_Symbol", "string"), ("_Period", "ENUM_TIMEFRAMES"), ("_Digits", "int"), ("_Point", "double"), ("_LastError", "int"),
               ("_StopFlag", "bool"), ("_UninitReason", "int"), ("_RandomSeed", "int")):
    rep("extern const %s %s;" % (ty, nm), "extern %s %s;" % (ty, nm))
rep("#define MQ_NUM2STR", "struct mqlstring; mqlstring rt_n2s_d(double); mqlstring rt_n2s_i(long long);\n#define MQ_NUM2STR")
rep("MQ_NUM2STR mqlstring(T) : s(0), n(0) {}",
    "MQ_NUM2STR mqlstring(T v) : s(0), n(0) { if(mq_arith<typename mq_nocv<T>::type>::rank >= 9) *this = rt_n2s_d((double)v); else *this = rt_n2s_i((long long)v); }")
rep("mqlstring& operator+=(const mqlstring& o) { return *this; }", "mqlstring& operator+=(const mqlstring& o);")
rep("mq_strcast(T) : mqlstring() {}", "mq_strcast(T v) : mqlstring() { if(mq_arith<typename mq_nocv<T>::type>::rank >= 9) *this = rt_n2s_d((double)v); else *this = rt_n2s_i((long long)v); }")
h = h.replace("#pragma clang system_header", "#pragma clang system_header\n// GENERATED by create_rt.py: executable runtime = mql5shim.h + rt_impl.h", 1)
h += "\n" + open(os.path.join(HERE, "rt_impl.h")).read()
open(os.path.join(HERE, "mql5rt.h"), "w").write(h)
print("mql5rt.h written", len(h))
