// Driver for the executable EA harness: driver BARS.csv [NAME=VALUE ...]   (TICK=x and DIGITS=n set the symbol, everything else is an EA input)
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

struct RtEv { int fill, fillL, exit, win; long long bi, armBar; double lim, stp, stp0, res; };
extern "C" {
int rt_SetInput(const char* name, double v);
void rt_load(int n, const long long* t, const double* o, const double* h, const double* l, const double* c, double tick, int digits);
void rt_reset();
int rt_look();
void rt_step(int s, RtEv* e);
void rt_stats(double* o);
}
// SetInput(name, value): assigns any EA input by name (the EA-side switch is generated by mq5rt.py)
static bool SetInput(const std::string& name, double v) { return rt_SetInput(name.c_str(), v) != 0; }

int main(int argc, char** argv)
{
   if(argc < 2) { std::fprintf(stderr, "usage: %s bars.csv [NAME=VALUE ...]\n", argv[0]); return 2; }
   std::vector<long long> t; std::vector<double> o, h, l, c;
   FILE* f = std::fopen(argv[1], "r");
   if(!f) { std::fprintf(stderr, "cannot open %s\n", argv[1]); return 2; }
   char line[512];
   while(std::fgets(line, sizeof line, f))
   {
      long long tt; double a, b, cc, d;
      if(std::sscanf(line, "%lld,%lf,%lf,%lf,%lf", &tt, &a, &b, &cc, &d) == 5) { t.push_back(tt); o.push_back(a); h.push_back(b); l.push_back(cc); c.push_back(d); }
   }
   std::fclose(f);
   double tick = 0.01; int digits = 2;
   std::vector<std::pair<std::string, double>> ov;
   ov.push_back({"InpServerTz", 1}); ov.push_back({"InpServerGMT", 2.0}); ov.push_back({"InpUserGMT", 5.5}); ov.push_back({"InpDraw", 0}); ov.push_back({"InpShowTable", 0});
   for(int i = 2; i < argc; i++)
   {
      std::string a = argv[i]; size_t p = a.find('=');
      if(p == std::string::npos) { std::fprintf(stderr, "bad arg %s\n", argv[i]); return 2; }
      std::string k = a.substr(0, p); double v = std::atof(a.c_str() + p + 1);
      if(k == "TICK") tick = v; else if(k == "DIGITS") digits = (int)v; else ov.push_back({k, v});
   }
   int n = (int)t.size();
   rt_load(n, t.data(), o.data(), h.data(), l.data(), c.data(), tick, digits);
   for(auto& kv : ov) if(!SetInput(kv.first, kv.second)) { std::fprintf(stderr, "unknown input %s\n", kv.first.c_str()); return 2; }
   rt_reset();
   int look = rt_look();
   for(int s = n - look - 1; s >= 1; s--)
   {
      RtEv e; rt_step(s, &e);
      if(e.fill) std::printf("FILL %lld %lld %d %.10g %.10g\n", e.bi, e.armBar, e.fillL ? 1 : -1, e.lim, e.stp);
      if(e.exit) std::printf("EXIT %lld %.10g\n", e.bi, e.res);
   }
   double st[12]; rt_stats(st);
   std::printf("STATS %.10g %.10g %.10g %.10g %.10g %.10g %.10g %.10g %.10g %.10g %.10g %.10g\n", st[0], st[1], st[2], st[3], st[4], st[5], st[6], st[7], st[8], st[9], st[10], st[11]);
   return 0;
}
